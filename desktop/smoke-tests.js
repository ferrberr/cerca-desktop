import fs from 'node:fs/promises';
import path from 'node:path';

export async function runSmoke(window,root,app) {
  try {
    const report = await window.webContents.executeJavaScript(`(async()=>{
      await window.cercaReady;
      const bootstrap=await window.cercaDesktop.bootstrap();
      const status=await window.cercaDesktop.health();
      if(!bootstrap.ok||!status.ok||!status.value.ready)throw new Error('Modelos o preload no disponibles');
      if(typeof window.require!=='undefined')throw new Error('Renderer sin aislamiento');
      document.querySelector('#search-input').value='MacBook Air M2';
      document.querySelector('#search-form').requestSubmit();
      const firstVisible=await new Promise((resolve,reject)=>{const started=Date.now();const tick=()=>{const count=document.querySelectorAll('.product-card').length;if(count)return resolve({count,searching:document.querySelector('#search-form button[type="submit"]').disabled});if(Date.now()-started>180000)return reject(new Error('No llegaron resultados progresivos'));setTimeout(tick,100);};tick();});
      if(!firstVisible.searching)throw new Error('Los productos solo se muestran al finalizar');
      const demoResult=await window.cercaLastSearch;
      if(demoResult?.targetResults!==100||demoResult.stopReason!=='exhausted'||document.querySelector('#match-summary strong').textContent!=='Fin del catálogo'||!document.querySelector('#match-summary p').textContent.includes('6 de 100 coincidencias'))throw new Error('El resumen debe indicar que el catálogo se agotó tras seis coincidencias');
      const count=document.querySelectorAll('.product-card').length;
      const reasons=[...document.querySelectorAll('.product-card .match-percent')].map(e=>e.textContent);
      if(count!==6)throw new Error('Se esperaban 6 equipos M2; recibidos '+count);
      if(reasons.some(r=>r.includes('Sin analizar')))throw new Error('No se ejecutó la IA');
      document.querySelector('#price-filter').click();
      document.querySelector('#price-form input[name="min"]').value='700';
      document.querySelector('#price-form input[name="max"]').value='800';
      document.querySelector('#price-form').requestSubmit();
      const priceFiltered=document.querySelectorAll('.product-card').length;
      if(priceFiltered!==3)throw new Error('El precio mínimo/máximo no filtra correctamente: '+priceFiltered);
      document.querySelector('#price-filter').click();
      document.querySelector('#price-form input[name="min"]').value='900';
      document.querySelector('#price-form input[name="max"]').value='800';
      document.querySelector('#price-form').requestSubmit();
      if(document.querySelector('#price-error').hidden)throw new Error('No se valida el rango de precios');
      document.querySelector('#price-form input[name="min"]').value='0';
      document.querySelector('#price-form input[name="max"]').value='900';
      document.querySelector('#price-form').requestSubmit();
      const first=document.querySelector('[data-save]');first.click();
      document.querySelector('[data-page="favorites"]').click();
      if(document.querySelectorAll('.product-card').length!==1)throw new Error('Guardados incorrectos');
      document.querySelector('[data-page="search"]').click();
      document.querySelector('#theme-toggle').click();document.querySelector('#theme-toggle').click();
      document.querySelector('#settings-button').click();
      const modelPanel=document.querySelectorAll('.model-row').length===3;
      if(!modelPanel)throw new Error('No se muestran los tres modelos en Preferencias');
      const target=document.querySelector('#match-target');
      target.value='150';
      target.dispatchEvent(new Event('change',{bubbles:true}));
      const preferences=await window.cercaDesktop.bootstrap();
      if(preferences.value.preferences['cerca-target']!==150)throw new Error('No se ha guardado el objetivo escogido');
      document.querySelector('#close-modal').click();
      const nativeNotification=await window.cercaDesktop.testNotification();
      if(!nativeNotification.ok)throw new Error(nativeNotification.error);
      const alert={id:9001,query:'MacBook Air M2',minPrice:650,price:700,condition:'Como nuevo',zone:'Barcelona',radius:50,enabled:true};
      const saved=await window.cercaDesktop.setPreference('cerca-alerts',[alert]);
      const persisted=await window.cercaDesktop.bootstrap();
      if(!saved.ok||persisted.value.preferences['cerca-alerts'][0].minPrice!==650||persisted.value.preferences['cerca-alerts'][0].query!==alert.query)throw new Error('No se guarda la alerta nativa');
      const blockedDemoAlerts=await window.cercaDesktop.checkAlerts();
      if(blockedDemoAlerts.ok)throw new Error('No deben notificarse productos de ejemplo');
      document.querySelector('#dataset-switch').value='imported';
      document.querySelector('#dataset-switch').dispatchEvent(new Event('change'));
      await new Promise(resolve=>setTimeout(resolve,200));
      document.querySelector('#search-input').value='play 5 consola';
      document.querySelector('#map-view').click();
      document.querySelector('#search-form').requestSubmit();
      const streamingCanvas=document.querySelector('#real-map');
      const streamingMapId=window.cercaMapDebug().instanceId;
      const importedResult=await window.cercaLastSearch;
      if(importedResult?.targetResults!==150||!document.querySelector('#match-summary p').textContent.includes('8 de 150 coincidencias'))throw new Error('El mapa debe usar el objetivo de Preferencias');
      if(document.querySelector('#real-map')!==streamingCanvas||window.cercaMapDebug().instanceId!==streamingMapId)throw new Error('El mapa se reconstruye durante la búsqueda progresiva');
      const streamingMapMarkers=window.cercaMapDebug().markers;
      if(streamingMapMarkers!==8)throw new Error('El mapa debe mostrar las ocho PS5 validadas');
      document.querySelector('#grid-view').click();
      const strictTitles=[...document.querySelectorAll('.product-card h3')].map(e=>e.textContent);
      if(strictTitles.length!==8)throw new Error('La búsqueda estricta debe mostrar ocho consolas PS5, recibidas: '+JSON.stringify(strictTitles));
      if(strictTitles.some(t=>/PS[1-4]\\b|PlayStation [1-4]|Nintendo|Xbox|FIFA|Lote de|Mando DualSense/i.test(t)))throw new Error('Se ha mostrado un producto incorrecto: '+JSON.stringify(strictTitles));
      document.querySelector('#toast').classList.remove('visible');
      return {bootstrap:true,streamingMapPreserved:true,streamingMapMarkers,strictTitles,streamingBeforeCompletion:firstVisible,priceFiltered,invalidPriceRangeBlocked:true,nativeNotification:true,alertPersisted:true,demoNotificationsBlocked:true,modelPanel, models:status.value,searchCount:count,reasons,rendererIsolated:typeof window.require==='undefined',title:document.title,url:location.href};
    })()`);
    await window.webContents.executeJavaScript('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
    const image = await window.webContents.capturePage();
    await fs.mkdir(path.join(root, 'test-results'), {recursive: true});
    await fs.writeFile(path.join(root, 'test-results/desktop.png'), image.toPNG());
    await fs.writeFile(path.join(root, 'test-results/desktop-smoke.json'), JSON.stringify(report, null, 2));
    console.log('CERCA_SMOKE_OK', JSON.stringify(report));
    app.quit();
  } catch (error) {console.error('CERCA_SMOKE_FAILED', error); app.exit(1);}
}

export async function runMapSmoke(window,root,app){
 try{
  const report=await window.webContents.executeJavaScript(`(async()=>{
   await window.cercaReady;
   const wait=async(predicate,timeout=20000)=>{const start=Date.now();while(!predicate()){if(Date.now()-start>timeout)throw new Error('Tiempo de espera agotado');await new Promise(r=>setTimeout(r,100));}};
   document.querySelector('#map-view').click();
   await wait(()=>window.cercaMapDebug&&window.cercaMapDebug().tiles>0);
   const initial=window.cercaMapDebug();
   const originalCanvas=document.querySelector('#real-map');
   document.querySelector('#map-place-query').value='Barcelona pendiente';
   document.querySelector('#sort-select').value='price-desc';
   document.querySelector('#sort-select').dispatchEvent(new Event('change'));
   if(document.querySelector('#real-map')!==originalCanvas||window.cercaMapDebug().instanceId!==initial.instanceId)throw new Error('Se ha reconstruido el mapa al ordenar');
   if(document.querySelector('#map-place-query').value!=='Barcelona pendiente')throw new Error('Se pierde el texto del buscador del mapa');
   if(initial.markers<1||initial.circleMeters!==50000)throw new Error('Marcadores o radio inicial incorrectos: '+JSON.stringify(initial));
   document.querySelector('.map-row-select').click();
   await wait(()=>document.querySelector('.leaflet-popup-content'));
   document.querySelector('.real-map-popup button').click();
   await wait(()=>document.querySelector('.detail-gallery'));
   if(!document.querySelector('.detail-description').textContent.trim())throw new Error('Falta descripción pública');
   if(document.querySelector('#gallery-main').getAttribute('src').startsWith('assets/'))throw new Error('La ficha no tiene una fotografía real');
   const photos=document.querySelectorAll('[data-photo]').length;document.querySelector('#gallery-next').click();document.querySelector('#gallery-prev').click();
   document.querySelector('#close-modal').click();
   document.querySelector('#price-filter').click();
   document.querySelector('#price-form input[name="min"]').value='1000';
   document.querySelector('#price-form input[name="max"]').value='1001';
   document.querySelector('#price-form').requestSubmit();
   const priceFiltered=window.cercaMapDebug();
   if(priceFiltered.instanceId!==initial.instanceId)throw new Error('Se reconstruye el mapa al filtrar precio');
   if(priceFiltered.markers!==0)throw new Error('El mapa no respeta el rango de precio');
   document.querySelector('#price-filter').click();
   document.querySelector('#price-form input[name="min"]').value='0';
   document.querySelector('#price-form input[name="max"]').value='900';
   document.querySelector('#price-form').requestSubmit();
   document.querySelector('#location-filter').click();
   document.querySelector('#location-form input[name="radius"]').value='10';document.querySelector('#location-form').requestSubmit();
   await wait(()=>window.cercaMapDebug().circleMeters===10000);
   const filtered=window.cercaMapDebug();if(filtered.instanceId!==initial.instanceId)throw new Error('Se reconstruye el mapa al filtrar radio');if(filtered.markers>initial.markers)throw new Error('El filtro de radio aumenta los resultados');
   document.querySelector('#location-filter').click();
   document.querySelector('#location-form input[name="radius"]').value='50';document.querySelector('#location-form').requestSubmit();
   document.querySelector('#map-place-query').value='Madrid';document.querySelector('#map-place-form').requestSubmit();
   await wait(()=>document.querySelector('#map-place-results .place-option'));
   const places=document.querySelectorAll('#map-place-results .place-option').length;
   document.querySelector('#map-place-results .place-option').click();
   const madrid=window.cercaMapDebug();
   if(Math.abs(madrid.center.latitude-40.4)>.3||Math.abs(madrid.center.longitude+3.7)>.3)throw new Error('La localidad no ha centrado el mapa: '+JSON.stringify(madrid));
   document.querySelector('#location-filter').click();
   document.querySelector('#location-form input[name="latitude"]').value='41.3851';document.querySelector('#location-form input[name="longitude"]').value='2.1734';document.querySelector('#location-form').requestSubmit();
   await wait(()=>window.cercaMapDebug().tiles>0);
   document.querySelector('#toast').classList.remove('visible');
   return {mapInstancePreserved:true,mapInputPreserved:true,initial,priceFiltered,filtered,madrid,places,photos,gallery:true,realDescription:true,publicPhotos:true,final:window.cercaMapDebug(),url:location.href};
  })()`);
  await window.webContents.executeJavaScript('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))');
  const image=await window.webContents.capturePage();
  await fs.writeFile(path.join(root,'test-results/map-desktop.png'),image.toPNG());
  await fs.writeFile(path.join(root,'test-results/map-smoke.json'),JSON.stringify(report,null,2));
  console.log('CERCA_MAP_OK',JSON.stringify(report));app.quit();
 }catch(error){console.error('CERCA_MAP_FAILED',error);app.exit(1);}
}
